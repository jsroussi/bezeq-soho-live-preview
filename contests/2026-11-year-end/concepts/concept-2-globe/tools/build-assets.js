// Bundles binary assets into classic scripts / CSS so index.html works from file:// with no fetch.
//   node tools/build-assets.js
// - fonts/fonts.css: Simpler as base64 @font-face (file:// font loads are blocked in some browsers)
// - data/textures.js: Earth textures as data URIs (WebGL refuses file:// image textures)
const fs = require('fs');
const path = require('path');

const site = path.join(__dirname, '..');
const platformFonts = path.join(site, '..', '..', '..', 'platform', 'public', 'fonts');
const b64 = (f) => fs.readFileSync(f).toString('base64');

const faces = [['Regular', 400], ['Bold', 700], ['Black', 900]].map(([n, w]) =>
  `@font-face{font-family:"Simpler";font-weight:${w};font-display:swap;` +
  `src:url(data:font/otf;base64,${b64(path.join(platformFonts, `Simpler-${n}.otf`))}) format("opentype")}`);
fs.writeFileSync(path.join(site, 'fonts', 'fonts.css'), faces.join('\n') + '\n');

const tex = {
  land: 'data:image/jpeg;base64,' + b64(path.join(__dirname, 'src', 'earth-land.jpg')),
  lights: 'data:image/jpeg;base64,' + b64(path.join(__dirname, 'src', 'earth-lights.jpg')),
};
fs.writeFileSync(path.join(site, 'data', 'textures.js'),
  '// Generated by tools/build-assets.js. Earth land mask + night lights (NASA, public domain).\n' +
  'window.TEXTURES = ' + JSON.stringify(tex) + ';\n');
console.log('fonts.css + textures.js written');
