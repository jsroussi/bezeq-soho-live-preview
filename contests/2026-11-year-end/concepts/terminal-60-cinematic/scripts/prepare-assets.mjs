// Copies the repository's own campaign assets into public/ (git-ignored) and extracts the verified contest data
// into src/data/contest.generated.json. Nothing is downloaded; every source is a file already in this repository.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const contestDir = resolve(root, '../..');
const platform = resolve(contestDir, '../platform');
const pub = join(root, 'public');

const copy = (from, to) => {
  if (!existsSync(from)) throw new Error(`missing source asset: ${from}`);
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
};

const contest = JSON.parse(readFileSync(join(contestDir, 'contest.json'), 'utf8'));
const ids = contest.journey.stops.map((s) => s.id);

for (const id of ids) {
  for (const suffix of ['', '-peak', '-phone', '-peak-phone']) copy(join(contestDir, 'site-photos', `${id}${suffix}.jpg`), join(pub, 'photos', `${id}${suffix}.jpg`));
}

for (const w of ['Light', 'Regular', 'Bold', 'Black']) copy(join(platform, 'public/fonts', `Simpler-${w}.otf`), join(pub, 'fonts', `Simpler-${w}.otf`));
for (const id of ids) {
  const f = join(platform, 'site/fonts/local', `${id}.woff2`);
  if (existsSync(f)) copy(f, join(pub, 'fonts/local', `${id}.woff2`));
}
for (const f of ['land-mask.jpg', 'night-lights.jpg', 'day.jpg']) copy(join(platform, 'site/earth', f), join(pub, 'earth', f));

// The official Bezeq logo (platform/brand/official/bezeq-logo-hebrew.svg), never redrawn: the viewBox cropped to its
// own bounding box and every fill swapped to white (its only ink is the ground's navy, so it would vanish). T3-7.
const logo = readFileSync(join(platform, 'brand/official/bezeq-logo-hebrew.svg'), 'utf8')
  .replace(/width="[^"]*" height="[^"]*" viewBox="[^"]*"/, 'width="254" height="434" viewBox="338 374 254 434"')
  .replace(/fill="rgb\([^"]*\)"/g, 'fill="#FFFFFF"');
if (!/viewBox="338 374 254 434"/.test(logo) || /fill="rgb/.test(logo)) throw new Error('official logo: crop or fill swap failed');
mkdirSync(join(pub, 'brand'), { recursive: true });
writeFileSync(join(pub, 'brand', 'bezeq-logo-white.svg'), logo);

const stops = contest.journey.stops.map((s) => ({
  id: s.id, he: s.he, country: s.country, ll: s.ll, start: s.start, end: s.end,
  localName: s.localName, palette: s.palette, accent: s.accent,
  landmark: s.landmark?.name,
}));

const data = {
  _source: 'Generated by scripts/prepare-assets.mjs from contest.json; do not edit by hand.',
  name: contest.name,
  period: contest.period,
  divisionLine: 'אגף סוהו • חשמל • שירותי דיגיטל',
  origin: { he: 'חולון', ll: [34.7961, 32.0163], note: 'Bezeq building, Ha-Manor 7, Holon (owner brief)' },
  stops,
  stampsUnit: contest.stamps?.unit?.many,
  managerTerminals: (contest.drawRouting?.managerDraws ?? []).map((d) => d.label),
  prizesStatus: contest.prizes?.status,
  prizesTeaser: contest.prizes?.teaser,
  peakDaysStatus: contest.rulesRevision?.peakDaysStatus,
};
writeFileSync(join(root, 'src/data/contest.generated.json'), JSON.stringify(data, null, 1) + '\n');
console.log(`prepared ${ids.length} stops, managers: ${data.managerTerminals.join(' | ')}`);
